    private class OtherRecycler extends RecyclerView.Adapter{

        private class OtherViewHolder extends RecyclerView.ViewHolder{
            TextView tittleText,numberCount;
            LinearLayout nextLayout;

            public OtherViewHolder(@NonNull View itemView) {
                super(itemView);

                tittleText=itemView.findViewById(R.id.tittleText);
                numberCount=itemView.findViewById(R.id.numberCount);
                nextLayout=itemView.findViewById(R.id.nextLayout);
            }
        }


        @NonNull
        @Override
        public RecyclerView.ViewHolder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
            LayoutInflater inflater=getLayoutInflater();
            View oView=inflater.inflate(R.layout.item_list,parent,false);

            return new OtherViewHolder(oView);
        }

        @Override
        public void onBindViewHolder(@NonNull RecyclerView.ViewHolder holder, int position) {

            OtherViewHolder holder1= (OtherViewHolder) holder;
            hashMap=arrayList.get(position);
            String tittle=hashMap.get("tittle");
            String des=hashMap.get("description");
            String num=hashMap.get("num");
            holder1.tittleText.setText(tittle);
            holder1.numberCount.setText(num);
            holder1.nextLayout.setOnClickListener(new View.OnClickListener() {
                @Override
                public void onClick(View v) {
                    Bundle bundle=getIntent().getExtras();
                    int val=bundle.getInt("val");
                    if (val==1){
                        HtView.TITTLE_Ht=tittle;
                        HtView.DESCRIPTION=des;
                        Intent intent=new Intent(Other_salat_activity.this,HtView.class);
                        startActivity(intent);
                    }else {
                        All_text_file.TL_TEXT=tittle;
                        All_text_file.ALL_TEXT=des;
                        Intent intent=new Intent(Other_salat_activity.this,All_text_file.class);
                        startActivity(intent);
                    }
                }
            });


        }

        @Override
        public int getItemCount() {
            return arrayList.size();
        }
    }


