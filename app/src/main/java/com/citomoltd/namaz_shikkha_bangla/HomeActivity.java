    private class HomeRecycler extends RecyclerView.Adapter{


        private class HomeViewHolder extends RecyclerView.ViewHolder{
            TextView tittleText,numberCount;
            LinearLayout nextLayout;

            public HomeViewHolder(@NonNull View itemView) {
                super(itemView);
                tittleText=itemView.findViewById(R.id.tittleText);
                numberCount=itemView.findViewById(R.id.numberCount);
                nextLayout=itemView.findViewById(R.id.nextLayout);
            }
        }

        @NonNull
        @Override
        public RecyclerView.ViewHolder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
            LayoutInflater inflater=getLayoutInflater();
            View hView= inflater.inflate(R.layout.item_list,parent,false);

            return new HomeViewHolder(hView);
        }

        @Override
        public void onBindViewHolder(@NonNull RecyclerView.ViewHolder holder, @SuppressLint("RecyclerView") int position) {

            HomeViewHolder holder1= (HomeViewHolder) holder;
            hashMap=arrayList.get(position);
            String tittle=hashMap.get("tittle");
            String des=hashMap.get("des");
            String num=hashMap.get("num");

            holder1.tittleText.setText(tittle);
            holder1.numberCount.setText(num);
            holder1.nextLayout.setOnClickListener(new View.OnClickListener() {
                @Override
                public void onClick(View v) {

                    Bundle bundle = getIntent().getExtras();
                    int val = bundle.getInt("val");


                    AdHelper.showAdIfNeeded(HomeActivity.this, () -> {

                        if (val==4){
                            if (position==0){
                                Content_list2.L2TITTLE=tittle;
                                Intent intent=new Intent(HomeActivity.this,Content_list2.class);
                                startActivity(intent);
                            }else {
                                V_file3.TITLe=tittle;
                                Intent intent=new Intent(HomeActivity.this,V_file3.class);
                                startActivity(intent);
                            }

                        } else if (val==24) {
                            if (position==1||position==3||position==4||position==5||position==8){
                                HtView.TITTLE_Ht=tittle;
                                HtView.DESCRIPTION=des;
                                Intent intent=new Intent(HomeActivity.this, HtView.class);
                                startActivity(intent);
                            }else {
                                All_text_file.TL_TEXT=tittle;
                                All_text_file.ALL_TEXT=des;
                                Intent intent=new Intent(HomeActivity.this,All_text_file.class);
                                startActivity(intent);
                            }

                        }else {
                            All_text_file.TL_TEXT=tittle;
                            All_text_file.ALL_TEXT=des;
                            Intent intent=new Intent(HomeActivity.this,All_text_file.class);
                            startActivity(intent);

                        }


                    });

                }
            });


        }

        @Override
        public int getItemCount() {
            return arrayList.size();
        }
    }

