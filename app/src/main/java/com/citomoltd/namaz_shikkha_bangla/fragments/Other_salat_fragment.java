    private class SetRecycler extends RecyclerView.Adapter{
        private class SetViewHolder extends RecyclerView.ViewHolder{
            TextView tittleText,numberCount;
            LinearLayout nextLayout;
            public SetViewHolder(@NonNull View itemView) {
                super(itemView);

                tittleText=itemView.findViewById(R.id.tittleText);
                numberCount=itemView.findViewById(R.id.numberCount);
                nextLayout=itemView.findViewById(R.id.nextLayout);
            }
        }

        @NonNull
        @Override
        public RecyclerView.ViewHolder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
            LayoutInflater inflater=getLayoutInflater();
            View oView=inflater.inflate(R.layout.item_list,parent,false);

            return new SetViewHolder(oView);
        }

        @Override
        public void onBindViewHolder(@NonNull RecyclerView.ViewHolder holder, @SuppressLint("RecyclerView") int position) {
            SetViewHolder viewHolder= (SetViewHolder) holder;
            hashMap=arrayList.get(position);
            String tittle=hashMap.get("Tittle");
            String num=hashMap.get("num");
            String des=hashMap.get("description");

            viewHolder.tittleText.setText(tittle);
            viewHolder.numberCount.setText(num);
            viewHolder.nextLayout.setOnClickListener(new View.OnClickListener() {
                @Override
                public void onClick(View v) {

                    AdHelper.showAdIfNeeded(requireActivity(),() -> {
                        if (position==0||position==1||position==2||position==3||position==4||position==5||position==6||position==8){
                            Intent intent=new Intent(getActivity(), Other_salat_activity.class);
                            Bundle bundle=new Bundle();
                            bundle.putInt("val",position);
                            intent.putExtras(bundle);
                            startActivity(intent);

                        }else {
                            All_text_file.TL_TEXT=tittle;
                            All_text_file.ALL_TEXT=des;
                            Intent intent=new Intent(getActivity(),All_text_file.class);
                            startActivity(intent);
                        }
                    });
                }
            });


        }

        @Override
        public int getItemCount() {
            return arrayList.size();
        }
    }

